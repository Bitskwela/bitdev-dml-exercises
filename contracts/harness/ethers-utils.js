/**
 * Pure value helpers of the mocked ethers v6 surface, plus the v5 removal map.
 *
 * Split from `chain-mock.js` so the stateful mocks (providers, contracts, the
 * call recorder) stay separate from the arithmetic, which is a total function
 * of its inputs and needs no fixture.
 */

/** Removed in ethers v6, keyed to the v6 replacement the student should use. */
const V5_REMOVALS = {
  providers:
    "ethers.providers.X — use ethers.BrowserProvider / ethers.JsonRpcProvider",
  utils:
    "ethers.utils.X — the helpers moved to the top level, e.g. ethers.parseUnits",
  constants: "ethers.constants.X — use ethers.ZeroAddress and friends",
  BigNumber: "ethers.BigNumber — v6 uses the native bigint type",
};

/** Error thrown when student code reaches for a removed ethers v5 API. */
function v5Error(name) {
  return new Error(
    `This exercise runs ethers v6, where ${V5_REMOVALS[name]}. Update your code to the v6 API.`,
  );
}

/**
 * Coerce a fixture value to what an ethers v6 call would return.
 *
 * A numeric string ending in `n` models a `uint256`, which v6 surfaces as a
 * native bigint rather than v5's BigNumber object.
 */
function fixtureValue(raw) {
  // Recurse into arrays so a tuple return — `contract.tasks(i)` destructured as
  // `[id, content, done]` — can mix bigints and plain values.
  if (Array.isArray(raw)) return raw.map(fixtureValue);
  if (typeof raw === "string" && /^-?\d+n$/.test(raw)) return BigInt(raw.slice(0, -1));
  return raw;
}

/**
 * A value as an ABI-decoded contract read returns it in v6.
 *
 * Every `intN`/`uintN` decodes to a bigint — `decimals()` is `18n`, not `18` —
 * so an integer a fixture author wrote as a plain JSON number is promoted.
 */
function abiValue(raw) {
  if (Array.isArray(raw)) return raw.map(abiValue);
  if (typeof raw === "number" && Number.isInteger(raw)) return BigInt(raw);
  return fixtureValue(raw);
}

/** The unit names v6 accepts in place of a decimals count. */
const UNIT_NAMES = ["wei", "kwei", "mwei", "gwei", "szabo", "finney", "ether"];

/** Resolve `"gwei"` → 9 and pass a number through, as v6's unit argument does. */
function unitDecimals(unit) {
  if (typeof unit !== "string") return Number(unit);
  const index = UNIT_NAMES.indexOf(unit);
  if (index < 0) throw new Error(`invalid unit (argument="unit", value=${JSON.stringify(unit)}, code=INVALID_ARGUMENT, version=6.13.4)`);
  return index * 3;
}

/** ethers.formatUnits — bigint to a decimal string. Unit is decimals or a name. */
function formatUnits(value, unit = 18) {
  const decimals = unitDecimals(unit);
  const scale = BigInt(10) ** BigInt(decimals);
  const signed = BigInt(value);
  const amount = signed < 0n ? -signed : signed;
  const whole = amount / scale;
  const frac = (amount % scale)
    .toString()
    .padStart(decimals, "0")
    .replace(/0+$/, "");
  const sign = signed < 0n ? "-" : "";
  // v6 prints no fraction at all for zero decimals: formatUnits(123n, 0) is "123".
  return decimals === 0 ? `${sign}${whole}` : `${sign}${whole}.${frac || "0"}`;
}

/** ethers.parseUnits — decimal string to bigint. Unit is decimals or a name. */
function parseUnits(value, unit = 18) {
  const decimals = unitDecimals(unit);
  const [whole, frac = ""] = String(value).split(".");
  const padded = frac.padEnd(decimals, "0").slice(0, decimals);
  return BigInt(whole + padded);
}

const MASK64 = (1n << 64n) - 1n;
const KECCAK_ROTC = [1, 3, 6, 10, 15, 21, 28, 36, 45, 55, 2, 14, 27, 41, 56, 8, 25, 43, 62, 18, 39, 61, 20, 44];
const KECCAK_PILN = [10, 7, 11, 17, 18, 3, 5, 16, 8, 21, 24, 4, 15, 23, 19, 13, 12, 2, 20, 14, 22, 9, 6, 1];
/** Keccak round constants, generated by the spec's LFSR rather than pasted in. */
const KECCAK_RC = (() => {
  const rc = [];
  let r = 1;
  for (let round = 0; round < 24; round += 1) {
    let c = 0n;
    for (let j = 0; j < 7; j += 1) {
      if (r & 1) c |= 1n << BigInt((1 << j) - 1);
      r = ((r << 1) ^ (r & 0x80 ? 0x71 : 0)) & 0xff;
    }
    rc.push(c);
  }
  return rc;
})();

const rotl64 = (v, n) => ((v << BigInt(n)) | (v >> BigInt(64 - n))) & MASK64;

/** Keccak-f[1600] over 25 bigint lanes, in place. */
function keccakF(s) {
  for (let round = 0; round < 24; round += 1) {
    const c = [0, 1, 2, 3, 4].map((x) => s[x] ^ s[x + 5] ^ s[x + 10] ^ s[x + 15] ^ s[x + 20]);
    for (let x = 0; x < 5; x += 1) {
      const d = c[(x + 4) % 5] ^ rotl64(c[(x + 1) % 5], 1);
      for (let y = 0; y < 25; y += 5) s[y + x] ^= d;
    }
    let current = s[1];
    for (let i = 0; i < 24; i += 1) {
      const j = KECCAK_PILN[i];
      const saved = s[j];
      s[j] = rotl64(current, KECCAK_ROTC[i]);
      current = saved;
    }
    for (let y = 0; y < 25; y += 5) {
      const row = s.slice(y, y + 5);
      for (let x = 0; x < 5; x += 1) s[y + x] = row[x] ^ (~row[(x + 1) % 5] & MASK64 & row[(x + 2) % 5]);
    }
    s[0] ^= KECCAK_RC[round];
  }
}

/**
 * keccak-256 of an ASCII string, as hex (no `0x`).
 *
 * Only `getAddress` needs it — an EIP-55 checksum is defined by this hash, so
 * there is no faithful shortcut. Slow (bigint lanes) but called a handful of
 * times per grading run, and dependency-free for QuickJS.
 */
function keccak256Ascii(text) {
  const RATE = 136;
  const bytes = [...String(text)].map((ch) => ch.charCodeAt(0) & 0xff);
  const padded = bytes.concat([0x01]);
  while (padded.length % RATE !== 0) padded.push(0);
  padded[padded.length - 1] |= 0x80;
  const state = new Array(25).fill(0n);
  for (let offset = 0; offset < padded.length; offset += RATE) {
    for (let lane = 0; lane < RATE / 8; lane += 1) {
      let v = 0n;
      for (let b = 7; b >= 0; b -= 1) v = (v << 8n) | BigInt(padded[offset + lane * 8 + b]);
      state[lane] ^= v;
    }
    keccakF(state);
  }
  let hex = "";
  for (let lane = 0; lane < 4; lane += 1) {
    for (let b = 0; b < 8; b += 1) hex += ((state[lane] >> BigInt(8 * b)) & 0xffn).toString(16).padStart(2, "0");
  }
  return hex;
}

/** An error shaped like v6's INVALID_ARGUMENT, so `e.code` checks behave. */
function invalidAddress(short, value) {
  const error = new Error(`${short} (argument="address", value=${JSON.stringify(value)}, code=INVALID_ARGUMENT, version=6.13.4)`);
  error.code = "INVALID_ARGUMENT";
  error.shortMessage = short;
  return error;
}

/**
 * ethers.getAddress — the EIP-55 checksummed form of an address.
 *
 * Mirrors v6: accepts it with or without `0x`, returns the checksum, and throws
 * `bad address checksum` for a mixed-case input whose casing is wrong.
 */
function getAddress(value) {
  if (typeof value !== "string" || !/^(0x)?[0-9a-fA-F]{40}$/.test(value)) {
    throw invalidAddress("invalid address", value);
  }
  const input = value.startsWith("0x") ? value : `0x${value}`;
  const lower = input.slice(2).toLowerCase();
  const hash = keccak256Ascii(lower);
  let checksummed = "0x";
  for (let i = 0; i < 40; i += 1) {
    checksummed += parseInt(hash[i], 16) >= 8 ? lower[i].toUpperCase() : lower[i];
  }
  if (/([A-F].*[a-f])|([a-f].*[A-F])/.test(input) && checksummed !== input) {
    throw invalidAddress("bad address checksum", value);
  }
  return checksummed;
}

/**
 * An array that also answers to its ABI names, like v6's `Result`.
 *
 * `tasks(i)` declared `returns (uint256 id, string content, bool done)` comes
 * back as something both `[id, content, done] = t` and `t.content` work on.
 * Names are non-enumerable so `Object.keys`, JSON and spreading still see a
 * plain array — as they do for the real `Result`. A name that would shadow an
 * array member (`length`, `map`, …) is skipped rather than allowed to break it.
 */
function toResult(values, names = []) {
  const result = values.slice();
  names.forEach((name, i) => {
    if (typeof name === "string" && name !== "" && !(name in result)) {
      Object.defineProperty(result, name, { value: result[i], enumerable: false });
    }
  });
  Object.defineProperty(result, "toArray", { value: () => values.slice(), enumerable: false });
  Object.defineProperty(result, "toObject", {
    value: () => Object.fromEntries(names.map((name, i) => [name, result[i]])),
    enumerable: false,
  });
  return result;
}

/**
 * Split a parameter list at its top-level commas: `uint a, (uint b, bool c) d`.
 * @returns The trimmed pieces; empty for `()`.
 */
function splitParams(list) {
  const parts = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < list.length; i += 1) {
    if (list[i] === "(") depth += 1;
    else if (list[i] === ")") depth -= 1;
    else if (list[i] === "," && depth === 0) {
      parts.push(list.slice(start, i));
      start = i + 1;
    }
  }
  parts.push(list.slice(start));
  return parts.map((p) => p.trim()).filter(Boolean);
}

/** The text inside the parentheses opening at `open`, and the index after them. */
function parenthesised(text, open) {
  let depth = 0;
  for (let i = open; i < text.length; i += 1) {
    if (text[i] === "(") depth += 1;
    else if (text[i] === ")" && (depth -= 1) === 0) return { inner: text.slice(open + 1, i), end: i + 1 };
  }
  return { inner: text.slice(open + 1), end: text.length };
}

const PARAM_MODIFIERS = new Set(["memory", "calldata", "storage", "indexed", "payable"]);

/** One human-readable parameter → `{ name, array, components? }`. */
function parseParam(text) {
  const tupleAt = text.startsWith("tuple(") ? 5 : text.startsWith("(") ? 0 : -1;
  if (tupleAt >= 0) {
    const { inner, end } = parenthesised(text, tupleAt);
    const rest = text.slice(end).trim();
    const array = rest.startsWith("[");
    const words = rest.replace(/^(\[\d*\])+/, "").trim().split(/\s+/).filter((w) => w && !PARAM_MODIFIERS.has(w));
    return { name: words[words.length - 1] || "", array, components: splitParams(inner).map(parseParam) };
  }
  const words = text.split(/\s+/).filter((w) => !PARAM_MODIFIERS.has(w));
  return { name: words.length > 1 ? words[words.length - 1] : "", array: /\[\d*\]$/.test(words[0] || "") };
}

/** A JSON-ABI parameter → the same shape as {@link parseParam}. */
function jsonParam(param) {
  const type = String((param && param.type) || "");
  return {
    name: (param && param.name) || "",
    array: /\[\d*\]$/.test(type),
    components: Array.isArray(param && param.components) ? param.components.map(jsonParam) : undefined,
  };
}

/**
 * The declared outputs of function `name` in a learner-supplied ABI, or null.
 *
 * Accepts both forms ethers does: human-readable strings and JSON fragments.
 * Never throws — an ABI this cannot read simply yields no names.
 */
function abiOutputs(abi, name) {
  let list = abi;
  if (typeof list === "string") {
    try {
      list = JSON.parse(list);
    } catch {
      return null;
    }
  }
  if (!Array.isArray(list)) return null;
  for (const item of list) {
    if (typeof item === "string") {
      const match = item.match(/^\s*function\s+([A-Za-z_$][\w$]*)\s*\(/);
      if (!match || match[1] !== name) continue;
      const at = item.indexOf("returns");
      if (at < 0) return [];
      const open = item.indexOf("(", at);
      return open < 0 ? [] : splitParams(parenthesised(item, open).inner).map(parseParam);
    }
    if (item && item.type === "function" && item.name === name) {
      return (item.outputs || []).map(jsonParam);
    }
  }
  return null;
}

/** Attach component names to a decoded tuple, recursing into nested tuples. */
function nameTuple(values, params) {
  const items = values.map((v, i) => namedValue(v, params[i]));
  return toResult(items, params.map((p) => (p && p.name) || ""));
}

/** One decoded value, named per its ABI parameter when it is a tuple. */
function namedValue(value, param) {
  if (!param || !param.components || !Array.isArray(value)) return value;
  if (param.array) return toResult(value.map((v) => (Array.isArray(v) ? nameTuple(v, param.components) : v)));
  return nameTuple(value, param.components);
}

/**
 * Shape a contract read's fixture value the way v6 returns it for this ABI.
 *
 * One output comes back unwrapped (a struct output is its own named Result);
 * several come back as a Result named by the outputs. Without a readable ABI
 * the value is returned as is.
 */
function shapeReturn(value, outputs) {
  if (!outputs || outputs.length === 0) return value;
  if (outputs.length === 1) return namedValue(value, outputs[0]);
  return Array.isArray(value) ? nameTuple(value, outputs) : value;
}

/** ethers.isAddress. */
function isAddress(value) {
  return /^0x[0-9a-fA-F]{40}$/.test(String(value));
}

/**
 * A deterministic 32-byte hash stand-in.
 *
 * Grading asserts that a value *was* hashed and threaded through, never that it
 * equals a specific keccak digest — so a stable placeholder is enough, and
 * avoids pulling a crypto implementation into the sandbox.
 */
function pseudoHash(value) {
  return `0x${String(value).length.toString(16).padStart(64, "0")}`;
}

